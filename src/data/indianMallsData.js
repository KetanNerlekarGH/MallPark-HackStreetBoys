export const STATES_LIST = [...new Set(INDIAN_MALLS_DATA.map((m) => m.state))].sort();

export function getCitiesByState(stateName) {
  if (!stateName) return [];
  const stateMalls = INDIAN_MALLS_DATA.filter((m) => m.state === stateName);
  return [...new Set(stateMalls.map((m) => m.city))].sort();
}

export function getMallsByCity(cityName, stateName) {
  if (!cityName) return [];
  return INDIAN_MALLS_DATA.filter((m) => m.city === cityName && (!stateName || m.state === stateName));
}

